"""
Traffic configs for the tests.

replay.py's -c takes either a path to a TOML config or the name of a built-in
one from configs/. A test whose traffic needs nothing but the protocol gets
the built-in config; the rest get one generated into the test's tmp_path.
Sender names are the ones configs/*.toml already declare, so a generated
config and a built-in one name their output directory the same way.
"""

import pathlib
from typing import Any, Dict, NamedTuple, Optional


class Cfg(NamedTuple):
    config: Any  # built-in config name, or path to a generated one
    sender: str


_SENDERS = {"udp": "UDP", "tcp": "TCP", "dot": "DoT", "doq": "DoQ"}

PROFILES: Dict[str, Dict[str, Dict[str, Any]]] = {
    "latency": {
        # Boundaries are milliseconds; the final boundary is timeout_s * 1000.
        "*": {
            "timeout_s": 2,
            "latency_bucket_boundaries": [100, 300, 600, 1000, 1500, 2000],
        },
    },
}


def sender_name(protocol: str, http_method: Optional[str] = None) -> str:
    if protocol == "doh":
        return "DoH-POST" if http_method == "POST" else "DoH-GET"
    return _SENDERS[protocol]


def _fmt(value: Any) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, str):
        return f'"{value}"'
    if isinstance(value, list):
        return "[" + ", ".join(_fmt(item) for item in value) + "]"
    return str(value)


def make_config(
    tmp_path: pathlib.Path,
    profile: str,
    protocol: str,
    doh_method: Optional[str] = None,
) -> Cfg:
    """
    The config for `profile` over `protocol`, and the sender name it declares.
    doh_method picks between configs/doh-get.toml and configs/doh-post.toml for
    the "default" profile, which is the only one whose callers disagree.
    """
    spec = PROFILES[profile]
    fields = {**spec.get("*", {}), **spec.get(protocol, {})}
    assert doh_method is None or not fields, "doh_method is for built-in configs"
    sender = sender_name(protocol, fields.get("http_method", doh_method))

    if not fields:
        return Cfg(sender.lower(), sender)

    lines = [
        f'# Generated by tests/testconfigs.py, profile "{profile}".',
        "[traffic]",
        "",
        f"[traffic.{sender}]",
        f'protocol = "{protocol}"',
    ]
    lines += [f"{key} = {_fmt(value)}" for key, value in fields.items()]

    path = tmp_path / f"{profile}_{protocol}.toml"
    path.write_text("\n".join(lines) + "\n")
    return Cfg(path, sender)
